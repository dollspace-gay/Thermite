/// Exact operation count for the immutable v1 profile. Additions require a new
/// registry version instead of silently widening the accepted platform.
pub const X86_64_PC_UEFI_SMP_V1_OPERATION_COUNT: usize = 104;

#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
pub enum PlatformDomain {
    Boot,
    Memory,
    Mmio,
    Pio,
    Irq,
    Cpu,
    Atomic,
    Smp,
    Dma,
    Clock,
    Entropy,
    Power,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct PlatformOperation {
    key: &'static str,
    pub signature: &'static str,
    pub contract: &'static str,
    pub domain: PlatformDomain,
    pub capability: Option<CapabilityKind>,
    pub rights: Rights,
    pub symbol: &'static str,
    pub source_contract_sha256: Option<&'static str>,
    pub source_reachable: bool,
    pub secondary_domains: &'static [PlatformDomain],
    pub abi: &'static str,
    pub alignment: u16,
    pub ownership: &'static str,
    pub model: &'static str,
    pub concurrency: &'static str,
    pub failure: &'static str,
    pub evidence: &'static str,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum RegistryError {
    UnknownName,
    DuplicateName,
    SignatureDrift,
    ContractDrift,
    DomainDrift,
    CapabilityDrift,
    RightsDrift,
    SymbolDrift,
    SourceContractDrift,
    ReachabilityDrift,
    MetadataDrift,
}

impl PlatformOperation {
    #[must_use]
    pub fn name(&self) -> &'static str {
        canonical_name(self.key)
    }

    pub fn exact_match(&self, candidate: &Self) -> Result<(), RegistryError> {
        if self.key != candidate.key {
            return Err(RegistryError::UnknownName);
        }
        if self.signature != candidate.signature {
            return Err(RegistryError::SignatureDrift);
        }
        if self.contract != candidate.contract {
            return Err(RegistryError::ContractDrift);
        }
        if self.domain != candidate.domain {
            return Err(RegistryError::DomainDrift);
        }
        if self.capability != candidate.capability {
            return Err(RegistryError::CapabilityDrift);
        }
        if self.rights != candidate.rights {
            return Err(RegistryError::RightsDrift);
        }
        if self.symbol != candidate.symbol {
            return Err(RegistryError::SymbolDrift);
        }
        if self.source_contract_sha256 != candidate.source_contract_sha256 {
            return Err(RegistryError::SourceContractDrift);
        }
        if self.source_reachable != candidate.source_reachable {
            return Err(RegistryError::ReachabilityDrift);
        }
        if self.secondary_domains != candidate.secondary_domains
            || self.abi != candidate.abi
            || self.alignment != candidate.alignment
            || self.ownership != candidate.ownership
            || self.model != candidate.model
            || self.concurrency != candidate.concurrency
            || self.failure != candidate.failure
            || self.evidence != candidate.evidence
        {
            return Err(RegistryError::MetadataDrift);
        }
        Ok(())
    }
}

pub fn lookup(name: &str) -> Result<&'static PlatformOperation, RegistryError> {
    let mut found = None;
    for entry in X86_64_PC_UEFI_SMP_V1 {
        if entry.name() == name {
            if found.is_some() {
                return Err(RegistryError::DuplicateName);
            }
            found = Some(entry);
        }
    }
    found.ok_or(RegistryError::UnknownName)
}

